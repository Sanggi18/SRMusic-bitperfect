/**
 * Creates the exact adaptive rounded corner shape matching SwitchAI preference drawables:
 * - TOP: 20dp top corners, 4dp bottom corners
 * - MIDDLE: 4dp all corners
 * - BOTTOM: 4dp top corners, 20dp bottom corners
 * - SINGLE: 20dp all corners
 */
fun groupItemShape(
    position: ItemPosition,
    cornerRadius: Dp = 20.dp,
    innerRadius: Dp = 4.dp
): RoundedCornerShape {
    return when (position) {
        ItemPosition.SINGLE -> RoundedCornerShape(cornerRadius)
        ItemPosition.TOP -> RoundedCornerShape(
            topStart = cornerRadius,
            topEnd = cornerRadius,
            bottomStart = innerRadius,
            bottomEnd = innerRadius
        )
        ItemPosition.MIDDLE -> RoundedCornerShape(innerRadius)
        ItemPosition.BOTTOM -> RoundedCornerShape(
            topStart = innerRadius,
            topEnd = innerRadius,
            bottomStart = cornerRadius,
            bottomEnd = cornerRadius
        )
    }
}

/**
 * Determines ItemPosition based on index and collection size
 */
fun getItemPosition(index: Int, total: Int): ItemPosition = when {
    total <= 1 -> ItemPosition.SINGLE
    index == 0 -> ItemPosition.TOP
    index == total - 1 -> ItemPosition.BOTTOM
    else -> ItemPosition.MIDDLE
}

@Composable
fun SettingsGroupItem(
    position: ItemPosition,
    modifier: Modifier = Modifier,
    content: @Composable () -> Unit
) {
    Card(
        modifier = modifier.fillMaxWidth(),
        shape = groupItemShape(position),
        colors = CardDefaults.cardColors(
            containerColor = MaterialTheme.colorScheme.surfaceContainer
        ),
        elevation = CardDefaults.cardElevation(defaultElevation = 0.dp)
    ) {
        content()
    }
}

